const PROVIDER_ICON_MAP: Record<
  ProviderIconKey,
  ComponentType<IconProps>
> = {
  google: GeminiIcon,
  openai: OpenAiIcon,
  anthropic: ClaudeIcon,
  moonshot: MoonshotIcon,
  deepseek: DeepSeekIcon,
};

/** Resolve provider slug from API/catalog or model_id prefix. */
export function resolveProviderIconKey(
  provider: string,
  modelId?: string,
): ProviderIconKey {
  const normalized = provider.toLowerCase();
  if (normalized in PROVIDER_ICON_MAP) {
    return normalized as ProviderIconKey;
  }
  const id = (modelId ?? '').toLowerCase();
  if (id.startsWith('gemini')) return 'google';
  if (id.startsWith('gpt')) return 'openai';
  if (id.startsWith('claude')) return 'anthropic';
  if (id.startsWith('kimi') || id.startsWith('moonshot')) return 'moonshot';
  if (id.startsWith('deepseek')) return 'deepseek';
  return 'google';
}

export function ProviderIcon({
  provider,
  modelId,
  className,
}: {
  provider: string;
  modelId?: string;
  className?: string;
}) {
  const key = resolveProviderIconKey(provider, modelId);
  const Icon = PROVIDER_ICON_MAP[key];
  return <Icon className={className} />;
}
